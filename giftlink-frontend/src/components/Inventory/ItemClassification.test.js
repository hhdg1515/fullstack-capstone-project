import React from 'react';
import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import ItemForm from './ItemForm';
import { taxonomy } from '../../test-support/catalogs';
import { selectItemType } from '../../test-support/selectItemType';
const plan = { status: 'active', moveOutDeadline: '2099-01-01' };
beforeEach(() => { global.fetch = jest.fn(async () => ({ ok: true, status: 200, json: async () => taxonomy })); });
const ready = async () => waitFor(() => expect(screen.getByLabelText('Item type')).not.toBeDisabled());
const saveDraft = () => fireEvent.submit(screen.getByRole('button', { name: 'Save Draft' }).closest('form'));
test('searches across categories and synonyms; choosing a type derives category and preserves condition', async () => {
  const save = jest.fn(); render(<ItemForm plan={plan} onSave={save} />); await ready();
  expect(screen.queryByLabelText('Category')).not.toBeInTheDocument();
  const field = screen.getByRole('combobox', { name: 'Item type' });
  fireEvent.change(field, { target: { value: 'tv' } });
  expect(screen.getByRole('option', { name: 'Television Living Room' })).toBeVisible();
  expect(screen.queryByRole('option', { name: 'Desk Office & Lighting' })).not.toBeInTheDocument();
  fireEvent.keyDown(field, { key: 'ArrowDown' }); fireEvent.keyDown(field, { key: 'Enter' });
  expect(field).toHaveValue('Television'); expect(field).toHaveFocus(); expect(field).toHaveAttribute('aria-expanded', 'false');
  fireEvent.change(screen.getByLabelText('Condition (optional)'), { target: { value: 'good' } });
  selectItemType('monitor');
  fireEvent.change(screen.getByLabelText('Item name'), { target: { value: 'Study display' } }); saveDraft();
  await waitFor(() => expect(save).toHaveBeenCalledTimes(1));
  expect(save.mock.calls[0][0]).toMatchObject({ categoryId: 'office-lighting', itemTypeId: 'monitor', condition: 'good' });
  expect(save.mock.calls[0][0]).not.toHaveProperty('category');
});
test('unknown terms offer global Other with optional validated short custom type', async () => {
  const save = jest.fn(); render(<ItemForm plan={plan} onSave={save} />); await ready();
  fireEvent.change(screen.getByLabelText('Item name'), { target: { value: 'Household equipment' } });
  fireEvent.change(screen.getByLabelText('Item type'), { target: { value: 'sewing machine' } });
  expect(screen.getByRole('status')).toHaveTextContent('No matching types. Choose Other.');
  fireEvent.click(screen.getByRole('option', { name: 'Other Other Household' }));
  const custom = screen.getByLabelText('Custom type (optional)');
  fireEvent.change(custom, { target: { value: '<script>' } }); saveDraft();
  expect(custom).toHaveFocus(); expect(custom).toHaveAttribute('aria-invalid', 'true'); expect(save).not.toHaveBeenCalled();
  fireEvent.change(custom, { target: { value: '  Sewing   machine  ' } }); saveDraft();
  await waitFor(() => expect(save).toHaveBeenCalledTimes(1));
  expect(save.mock.calls[0][0]).toMatchObject({ categoryId: 'other-household', itemTypeId: 'other', customItemType: 'Sewing machine' });
});
test('category-specific Other, clear and replacement remove stale custom values without changing unrelated drafts', async () => {
  const save = jest.fn(); render(<ItemForm plan={plan} onSave={save} />); await ready();
  selectItemType('living-room-other');
  fireEvent.change(screen.getByLabelText('Custom type (optional)'), { target: { value: 'Footrest' } });
  selectItemType('sofa'); expect(screen.queryByLabelText('Custom type (optional)')).not.toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Clear item type' }));
  fireEvent.keyDown(screen.getByLabelText('Item type'), { key: 'Escape' });
  fireEvent.change(screen.getByLabelText('Item name'), { target: { value: 'Draft' } }); saveDraft();
  await waitFor(() => expect(save).toHaveBeenCalled());
  expect(save.mock.calls[0][0]).toMatchObject({ categoryId: null, itemTypeId: null, customItemType: null });
});
test('legacy categories and existing canonical/custom drafts remain unchanged without selection', async () => {
  const save = jest.fn(); const { rerender } = render(<ItemForm plan={plan} item={{ name: 'Existing desk', category: 'Old Furniture', status: 'draft' }} onSave={save} />); await ready();
  expect(screen.getByText('Existing category: Old Furniture. It will be preserved.')).toBeInTheDocument();
  expect(screen.getByLabelText('Item type')).toHaveValue(''); saveDraft();
  await waitFor(() => expect(save).toHaveBeenCalledTimes(1)); expect(save.mock.calls[0][0]).not.toHaveProperty('category');
  rerender(<ItemForm key="existing" plan={plan} item={{ name: 'Custom draft', status: 'draft', classification: { category: { id: 'other-household' }, itemType: { id: 'other' }, customItemType: 'Sewing machine' } }} onSave={save} />); await ready();
  expect(screen.getByLabelText('Item type')).toHaveValue('Other'); expect(screen.getByLabelText('Custom type (optional)')).toHaveValue('Sewing machine');
  saveDraft(); await waitFor(() => expect(save).toHaveBeenCalledTimes(2));
  expect(save.mock.calls[1][0]).toMatchObject({ categoryId: 'other-household', itemTypeId: 'other', customItemType: 'Sewing machine' });
});
test('uncommitted search cannot publish an invented type; Escape and Tab never select or submit it', async () => {
  const save = jest.fn(); render(<ItemForm plan={plan} onSave={save} />); await ready();
  fireEvent.change(screen.getByLabelText('Item name'), { target: { value: 'Item' } });
  fireEvent.change(screen.getByLabelText('Item type'), { target: { value: 'not listed' } });
  fireEvent.keyDown(screen.getByLabelText('Item type'), { key: 'Enter' }); expect(save).not.toHaveBeenCalled();
  fireEvent.keyDown(screen.getByLabelText('Item type'), { key: 'Escape' });
  saveDraft(); expect(save).not.toHaveBeenCalled();
  expect(screen.getByLabelText('Item type')).toHaveAccessibleDescription('Choose a listed type or Other, or clear the search to save without a type.');
  fireEvent.click(screen.getByRole('button', { name: 'Publish' }));
  expect(save).not.toHaveBeenCalled(); expect(screen.getByLabelText('Item type')).toHaveFocus();
});

test('malformed search metadata fails safely and catalog retry retains the name-only draft', async () => {
  const save = jest.fn();
  global.fetch = jest.fn(async () => ({ ok: true, status: 200, json: async () => ({ ...taxonomy, categories: [{ id: 'bad', label: 'Bad', itemTypes: [{ id: 'bad', label: 'Bad', searchTerms: [1] }] }] }) }));
  render(<ItemForm plan={plan} onSave={save} />);
  fireEvent.change(screen.getByLabelText('Item name'), { target: { value: 'Keep this draft' } });
  await screen.findByRole('button', { name: 'Retry item types' });
  expect(screen.getByLabelText('Item type')).toBeDisabled();
  global.fetch = jest.fn(async () => ({ ok: true, status: 200, json: async () => taxonomy }));
  fireEvent.click(screen.getByRole('button', { name: 'Retry item types' })); await ready();
  expect(screen.getByLabelText('Item name')).toHaveValue('Keep this draft'); saveDraft();
  await waitFor(() => expect(save).toHaveBeenCalledTimes(1));
  expect(save.mock.calls[0][0]).toMatchObject({ name: 'Keep this draft', categoryId: null, itemTypeId: null });
});
